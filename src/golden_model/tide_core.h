/*
 * tide_core.h -- TIDE-EKF C golden model (Agent 1, gate G1)
 *
 * Bit-exact reference for the microcode / RTL.  Build:
 *     gcc -O2 -std=c99 -ffp-contract=off -o tide_core.exe tide_core.c
 *
 * Every floating-point operation goes through a hw_* primitive that mirrors
 * the FP lane contract (doc 16 / doc 19):
 *   - IEEE-754 binary32, RNE, subnormals supported, NO fused multiply-add
 *   - any NaN result is the canonical qNaN 0x7FC00000 (no payloads)
 *   - FABS(NaN)=0x7FC00000, FNEG(NaN)=0xFFC00000 (doc 16 sec 3)
 *   - FMIN/FMAX return the non-NaN operand; ties return operand a (A-FMM)
 * The ORDER of operations in tide_core.c is normative: the microcode
 * (the .tasm files under microcode/, generated by microcode/gen_ucode.py) perform the same
 * operations in the same association order.
 */
#ifndef TIDE_CORE_H
#define TIDE_CORE_H

#include <stdint.h>
#include <string.h>

typedef struct {
    uint32_t t_last;     /* ctx word 0            */
    float    x[6];       /* ctx words 1..6        */
    float    P[21];      /* ctx words 7..27, packed lower triangle row-major */
} tide_ctx_t;

typedef struct {
    uint32_t t_event;    /* microseconds */
    float    z[4];       /* range, azimuth, elevation, doppler */
    float    R[4];       /* measurement variances (diagonal)   */
} tide_event_t;

typedef struct {
    float qp, qv, dt0inv;  /* MMIO 0x34 / 0x38 / 0x3C */
} tide_cfg_t;

/* Scratch rows exchanged between GEOM and the scalar loop:
 * row k = { h0..h5, R_k, y0_k }.  Stored at TIDE-RAM word SCRATCH_ROWS+8k. */
typedef struct {
    float row[4][8];
} tide_rows_t;

/* Debug taps (optional, may be NULL) */
typedef struct {
    tide_ctx_t  pre;     /* ctx after PREDICT (t_last unchanged) */
    tide_rows_t rows;    /* GEOM output                          */
} tide_dbg_t;

/* ---- Constant ROM (final contents, see ASSUMPTIONS A-ROM) ------------- */
extern const uint32_t TIDE_ROM[64];
enum {
    ROM_PI = 0, ROM_PI_2 = 1, ROM_TWO_PI = 2, ROM_NEG_PI = 3, ROM_ONE = 4,
    ROM_ZERO = 5, ROM_NEG_ONE = 6, ROM_US_TO_S = 7, ROM_TAN_PI_8 = 8,
    ROM_COT_PI_8 = 9, ROM_PI_4 = 10,
    ROM_ATAN_H0 = 11, ROM_ATAN_H1 = 12, ROM_ATAN_H2 = 13, ROM_ATAN_H3 = 14,
    ROM_FLOOR = 15, ROM_EPS = 16, ROM_HALF = 17, ROM_TWO = 18, ROM_NEG_TWO = 19
};

/* TIDE-RAM word addresses (memmap.yaml) */
#define TIDE_RAM_COMMITTED  0x240
#define TIDE_RAM_SHADOW     0x260
#define TIDE_RAM_SCRATCH    0x280   /* microcode-owned scratch, A-SCRATCH */
#define TIDE_RAM_QUERY_OUT  0x280   /* t, x0..x5                          */
#define TIDE_RAM_ROWS       0x300   /* 4 rows x 8 words                   */

static inline uint32_t f2u(float f) { uint32_t u; memcpy(&u, &f, 4); return u; }
static inline float    u2f(uint32_t u) { float f; memcpy(&f, &u, 4); return f; }
static inline float    rom(int i) { return u2f(TIDE_ROM[i]); }

/* ---- hardware-faithful primitives ------------------------------------ */
static inline float hw_canon(float r) { return (r != r) ? u2f(0x7FC00000u) : r; }
static inline float hw_add(float a, float b) { return hw_canon(a + b); }
static inline float hw_sub(float a, float b) { return hw_canon(a - b); }
static inline float hw_mul(float a, float b) { return hw_canon(a * b); }
float hw_div(float a, float b);
float hw_sqrt(float a);
static inline float hw_fabs(float a) { return (a != a) ? u2f(0x7FC00000u) : u2f(f2u(a) & 0x7FFFFFFFu); }
static inline float hw_fneg(float a) { return (a != a) ? u2f(0xFFC00000u) : u2f(f2u(a) ^ 0x80000000u); }
static inline float hw_fmax(float a, float b) {
    if (a != a && b != b) return u2f(0x7FC00000u);
    if (a != a) return b;
    if (b != b) return a;
    return (a < b) ? b : a;
}
static inline float hw_fmin(float a, float b) {
    if (a != a && b != b) return u2f(0x7FC00000u);
    if (a != a) return b;
    if (b != b) return a;
    return (b < a) ? b : a;
}
/* FCMP -> integer flag, then ITOF: 1.0f / 0.0f (ordered less-than) */
static inline float hw_lt(float a, float b) { return (a < b) ? 1.0f : 0.0f; }
static inline float hw_itof(int32_t i) { return (float)i; }

/* ---- API --------------------------------------------------------------- */
float tide_atan2_full(float y, float x);   /* azimuth  (any quadrant, 0,0 -> +0) */
float tide_atan2_xpos(float y, float x);   /* elevation (x > 0 guaranteed)       */
float tide_atan2_ref (float y, float x);   /* branchy doc-19 reference (tests)   */

void tide_predict(tide_ctx_t *c, int32_t dt_us, const tide_cfg_t *cfg);
void tide_geom(const float x[6], const float z[4], const float R[4], tide_rows_t *rows);
void tide_scalar(tide_ctx_t *c, const float row[8], const float xp[6]);
void tide_unit(tide_ctx_t *c, const tide_event_t *e, const tide_cfg_t *cfg, tide_dbg_t *dbg);
/* QUERY: predict-only, non-destructive.  out[0]=t_q bits, out[1..6]=x */
void tide_query(const tide_ctx_t *c, uint32_t t_q, const tide_cfg_t *cfg, uint32_t out[7]);

#define TIDE_PIDX(i, j) ((i) * ((i) + 1) / 2 + (j))   /* i >= j */

#endif
